import mongoose from "mongoose";

const { Schema } = mongoose;

export const ANSWER_STATUSES = ["correct", "wrong", "unanswered", "partial", "pending"];
export const AWAY_TYPES = ["hidden", "blur", "closed"];

const answerSchema = new Schema(
  {
    n: { type: Number, required: true },
    qid: { type: String, maxlength: 80 },
    type: { type: String, enum: ["choice", "written"], required: true },
    prompt: { type: String, maxlength: 600 },
    given: { type: String, maxlength: 300, default: null },
    correct: { type: String, maxlength: 300 },
    status: { type: String, enum: ANSWER_STATUSES, required: true },
    points: { type: Number, default: 0 },
    maxPoints: { type: Number, default: 1 },
    /** true when the student graded an open question themselves */
    selfScored: { type: Boolean, default: false },
  },
  { _id: false },
);

const awaySchema = new Schema(
  {
    from: { type: Date, required: true },
    to: { type: Date, required: true },
    ms: { type: Number, required: true },
    type: { type: String, enum: AWAY_TYPES, required: true },
    /** question number the student was on when they left */
    q: { type: Number },
  },
  { _id: false },
);

const attemptSchema = new Schema(
  {
    student: { type: Schema.Types.ObjectId, ref: "Student", required: true, index: true },
    /** id generated by the browser, makes every save idempotent */
    clientId: { type: String, required: true, maxlength: 64 },

    /* denormalised for the teacher view and the sheet */
    studentName: { type: String },
    studentGrade: { type: Number },
    school: { type: String },

    kind: { type: String, enum: ["exam", "chapter"], required: true },
    testId: { type: String, required: true, maxlength: 40 },
    title: { type: String, required: true, maxlength: 200 },
    testGrade: { type: Number, min: 1, max: 12 },
    chapterId: { type: String, maxlength: 20 },

    status: { type: String, enum: ["in_progress", "submitted"], default: "in_progress", index: true },
    startedAt: { type: Date, required: true },
    finishedAt: { type: Date },
    lastActiveAt: { type: Date },
    timeLimitSec: { type: Number },
    durationSec: { type: Number },
    autoSubmitted: { type: Boolean, default: false },

    questionCount: { type: Number, default: 0 },
    answeredCount: { type: Number, default: 0 },
    score: { type: Number, default: 0 },
    maxScore: { type: Number, default: 0 },
    percent: { type: Number, default: 0 },
    counts: {
      correct: { type: Number, default: 0 },
      wrong: { type: Number, default: 0 },
      unanswered: { type: Number, default: 0 },
      partial: { type: Number, default: 0 },
      pending: { type: Number, default: 0 },
    },
    answers: { type: [answerSchema], default: [] },

    /** leaving the test tab: how often, for how long, and when */
    focus: {
      leaves: { type: Number, default: 0 },
      awayMs: { type: Number, default: 0 },
      longestMs: { type: Number, default: 0 },
      events: { type: [awaySchema], default: [] },
    },

    client: { tz: String, ua: String },

    sheets: {
      status: { type: String, enum: ["pending", "synced", "error", "off"], default: "pending", index: true },
      syncedAt: { type: Date },
      error: { type: String },
    },
  },
  { timestamps: true },
);

attemptSchema.index({ student: 1, clientId: 1 }, { unique: true });
attemptSchema.index({ status: 1, finishedAt: -1 });
attemptSchema.index({ testGrade: 1, kind: 1 });

export const Attempt = mongoose.models.Attempt || mongoose.model("Attempt", attemptSchema);
