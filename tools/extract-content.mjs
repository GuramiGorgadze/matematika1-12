#!/usr/bin/env node
/**
 * Extracts the content engine from the original single-file app (index.html)
 * into three ES modules under client/src/content/pack/:
 *
 *   core.js    answer checker (CHK), problem generators (GEN), LaTeX→MathML (MATHML),
 *              SVG figure builders (FIG, FIGV, FIGX, GEO), every lesson, every problem
 *              and generator, and the curriculum map (CURR) for grades 7, 8 and 11.
 *   exams.js   grade 12 national exams 2023–2026, their figures, and the practice-test generator.
 *   boards.js  the four interactive boards (graphs & geometry, trigonometry, 3D solids, vectors)
 *              and the expression parser they use.
 *
 * The original code was written for one shared global scope. Each module keeps the
 * original source verbatim inside module scope and adds explicit imports/exports, so the
 * content can still be edited in the original file and re-extracted.
 *
 * Usage:  node tools/extract-content.mjs path/to/original/index.html [outDir]
 */
import fs from "node:fs";
import path from "node:path";

const [src, outArg] = process.argv.slice(2);
if (!src) {
  console.error("Usage: node tools/extract-content.mjs <original index.html> [outDir]");
  process.exit(1);
}
const outDir = path.resolve(outArg || path.join(path.dirname(new URL(import.meta.url).pathname), "../client/src/content/pack"));
const html = fs.readFileSync(src, "utf8");

const scripts = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map((m) => m[1]);
const content = scripts.find((s) => s.includes("var CHK = (function"));
const app = scripts.find((s) => s.includes("var PROF = (function"));
if (!content || !app) throw new Error("Could not find the content or the app <script> block.");

function between(text, startMarker, endMarker, { includeStart = true } = {}) {
  const a = text.indexOf(startMarker);
  if (a < 0) throw new Error("Marker not found: " + startMarker);
  const b = text.indexOf(endMarker, a + startMarker.length);
  if (b < 0) throw new Error("Marker not found: " + endMarker);
  return text.slice(includeStart ? a : a + startMarker.length, b);
}

/* ---------- core ---------- */
const curr = between(app, "  var CURR = {", "  var GTOOLS");
const banner = (what) =>
  `/* eslint-disable */\n/**\n * GENERATED by tools/extract-content.mjs from the original single-file app — ${what}.\n * Edit the original and re-run the tool, or edit here directly (then stop re-extracting).\n */\n`;

const core =
  banner("content engine, lessons, problems, curriculum") +
  content.trim() +
  "\n\n/* ---------- curriculum map (grades 7, 8, 11) ---------- */\n" +
  curr.replace(/^ {2}/gm, "") +
  "\nexport { CHK, GEN, MATHML, FIG, FIGV, FIGX, GEO, R, PROBS, LES, SECTIONS, VSECTIONS, STSECTIONS, SPSECTIONS, EXSECTIONS, CURR };\n";

/* ---------- exams ---------- */
const examsSrc = between(app, "var EXFIGS = ", "/* ===== 12th grade: online timed tests");
const exams =
  banner("grade 12 national exams and practice tests") +
  'import { GEN, R } from "./core.js";\n\n' +
  examsSrc.trim() +
  "\n\nexport { EXAMS, EXFIGS, LETTERS };\n";

/* ---------- boards ---------- */
const parser = between(app, "/*PARSER-START*/", "/*PARSER-END*/", { includeStart: false });
const boardSrc = between(app, "  /* ---------- graph and geometry board ---------- */", "var EXFIGS = ");
const boards =
  banner("interactive boards: graphs & geometry, trigonometry, 3D solids, vectors") +
  parser.trim() +
  '\n\nfunction esc(s) { return String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;"); }\n\n' +
  boardSrc.replace(/^ {2}/gm, "").trim() +
  "\n\nexport { compileExpr, toolsHTML, mountTool, trigHTML, mountTrig, tool3dHTML, mount3D, toolVecHTML, mountVec };\n";

fs.mkdirSync(outDir, { recursive: true });
for (const [name, code] of [["core.js", core], ["exams.js", exams], ["boards.js", boards]]) {
  fs.writeFileSync(path.join(outDir, name), code);
  console.log(`${name.padEnd(10)} ${(code.length / 1024).toFixed(0).padStart(5)} KB`);
}
